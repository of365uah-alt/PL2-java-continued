    /**
     * Método para sustituir los "info" por la información real
     */
    private void cargarDatosDeReserva() {
        // Rellenamos los datos de la actividad
        jLabelActividad.setText(actividad.getTitulo());
        jLabelTipo.setText(String.valueOf(actividad.getTipo())); 
        jLabelMonitor.setText(actividad.getMonitor());
        jLabelSala.setText(actividad.getSala().getNombre());
        jLabelHorario.setText(actividad.getHorario().toString());
        
        // Rellenamos los datos del socio
        jLabelSocio.setText(socio.getNombre());
        
        // Calculamos el coste considerando si es especial y si el socio es VIP
        if (actividad.esEspecial()) {
            ActividadEspecial ae = (ActividadEspecial) actividad;
            // Usamos el método calcular precio para saber el método
            double precioFinal = socio.calcularPrecio(ae.getPrecio());
            jLabelCoste.setText(String.format("%.2f €", precioFinal));
        } else {
            jLabelCoste.setText("Incluido en tu cuota mensual");
        }
        
        jLabelDiasDisponibles.setText("Horario original: " + actividad.getHorario().toString());
        this.pack();
    }

